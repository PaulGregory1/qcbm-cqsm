"""Metric table of the four reference kernels -> reports/references.md and runs/references.json.

Run: ./.venv/bin/python scripts/references.py
"""

import json
from pathlib import Path

from archb.metrics import all_metrics
from archb.ou import OU, load_dataset
from archb.references import REFERENCE_NAMES, fit_ar1, reference_kernels

ROOT = Path(__file__).resolve().parents[1]
COLUMNS = [  # (key, header, format)
    ("weighted_tv", "Weighted TV", "{:.4f}"),
    ("tail_tv", "Tail TV", "{:.4f}"),
    ("stationary_tv", "Stationary TV", "{:.4f}"),
    ("lag1_acf", "Lag-1 acf", "{:.4f}"),
    ("acf_err", "ACF error (1–20)", "{:.4f}"),
    ("slope", "Cond.-mean slope", "{:.4f}"),
]
LABELS = {"exact": "Exact P*", "ar1": "Gaussian AR(1)", "tabular": "Tabular counts", "iid": "i.i.d. oracle"}


def main():
    data = load_dataset()
    kernels = reference_kernels(data)
    c, m, s = fit_ar1(data["N"])
    table = {name: all_metrics(kernels[name], kernels["exact"]) for name in REFERENCE_NAMES}
    lag1_exact = table["exact"]["lag1_acf_exact"]

    head = "| Reference | " + " | ".join(h for _, h, _ in COLUMNS) + " |"
    rows = [head, "| --- |" + " ---: |" * len(COLUMNS)]
    for name in REFERENCE_NAMES:
        cells = [f.format(table[name][k]) for k, _, f in COLUMNS]
        rows.append(f"| {LABELS[name]} | " + " | ".join(cells) + " |")
    md_table = "\n".join(rows)
    print(md_table)
    print(f"AR(1) fit: c={c:.4f} m={m:.4f} s={s:.4f} (true c={OU.c:.4f} m={OU.m:.4f} s={OU.s:.4f})")

    md = (
        "# Reference metrics\n\n"
        "Generated by `scripts/references.py`; all metrics are exact functions of the 32 × 32 kernels, "
        "scored against P*.\n\n"
        f"{md_table}\n\n"
        f"- Exact chain lag-1 autocorrelation: {lag1_exact:.4f} (true OU c = {OU.c:.4f}).\n"
        f"- Fitted AR(1) on bin centres: c = {c:.4f}, m = {m:.4f}, s = {s:.4f} "
        f"(true {OU.c:.4f}, {OU.m:.4f}, {OU.s:.4f}).\n"
        "- Tail TV averages the 16 rows with |z| > 1.41; slope uses π*-weighted least squares.\n"
    )
    (ROOT / "reports" / "references.md").write_text(md)
    out = {"metrics": table, "ar1_fit": {"c": c, "m": m, "s": s},
           "data_seed": data["seed"], "n_transitions": data["n_transitions"]}
    (ROOT / "runs" / "references.json").write_text(json.dumps(out, indent=2) + "\n")


if __name__ == "__main__":
    main()
