w("## Deviations from the plan\n")
w("- **New gates start at N(0, 0.2²)**, the spec's rule for every non-copy angle, not at 0 as the plan's variant "
  "paragraph said; the copy gates are π and each ancilla's layer-0 R_y is π/2 + noise, as planned. With noise the "
  "starting kernel is less close to the identity for the larger circuits (diagonal mass 0.26 for allpairs, 0.44 "
  "for inout, against 0.69 for B0, at seed 0).")
w("- **Step 0 optimizer: Adam (2,000 steps, best iterate kept) then L-BFGS-B (up to 20,000 iterations)** instead "
  "of Adam for 5,000 steps. A first B0 run with Adam alone was not converged at 5,000 steps (loss still falling "
  "0.5–7% per 500 steps) and some fits jumped out of a good basin (binary init 0: KL 0.09 at step 1,000, 0.35 at "
  "5,000). The step 0 numbers above are from the Adam + L-BFGS protocol only.")
w("- **Maximum-likelihood runs added** (`mle`, `mle_adam`), not in the plan: they keep the data and change only "
  "the objective (and then the optimizer), which is what finding 3 and 4 needed.")
w("- **inout: 5 initializations** (noise 0.2) instead of 10. Its input qubits are targets, so it needs the full "
  "10-qubit simulation, about 30× slower per step than the other circuits.")
w("- **Stop rule on a 25-step moving average** and a 1,500-step cap for Sinkhorn training, as planned. "
  "The warm start keeps every other training setting.\n")

