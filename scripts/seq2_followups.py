"""Sequence 2 follow-ups: render reports/seq2_followups.md and figs/seq2fu_*.png from runs/seq2/** metrics.
Every number is read from the runs.

  1. var2d inter-coordinate correlation: anc2 vs anc2x (cross entanglers) vs anc2 with interleaved bits, at
     2 x 4 bits (reduced protocol), plus anc2 at 2 x 3 bits.
  2. merton depth: anc2 with 3, 4, 5 layers (fit to P*, maximum likelihood).

Run: ./.venv/bin/python scripts/seq2_followups.py
"""

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

from archb import targets as TG  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
SEQ2, FIGS = ROOT / "runs" / "seq2", ROOT / "figs"
OI = {"black": "#000000", "orange": "#E69F00", "sky": "#56B4E9", "green": "#009E73",
      "blue": "#0072B2", "vermillion": "#D55E00", "purple": "#CC79A7", "grey": "#999999"}


def runs(target, mode, circuit):
    out = []
    for p in sorted((SEQ2 / target / mode / circuit).glob("*/metrics.json")):
        r = json.loads(p.read_text())
        r["dir"] = p.parent
        out.append(r)
    return out


def best(rs):
    return min(rs, key=lambda r: r["objective"]) if rs else None


def med(rs, key):
    return float(np.median([r["metrics"][key] for r in rs])) if rs else float("nan")


def f(x, n=3):
    return "–" if x is None or (isinstance(x, float) and np.isnan(x)) else f"{x:.{n}f}"


def lagerr(m, d):
    return max(abs(m[f"lag1_{k}"] - m[f"lag1_exact_{k}"]) for k in range(d))


REFS = {}


def refs(T):
    if T.name not in REFS:
        K, _ = TG.reference_kernels(T, TG.load_dataset(T))
        REFS[T.name] = {r: TG.metrics(K[r], T, K["exact"]) for r in ("parametric", "tabular")}
    return REFS[T.name]


L = []
w = L.append
w("# Sequence 2 follow-ups — inter-coordinate correlation (var2d) and depth (merton)\n")
w("Generated by `scripts/seq2_followups.py` from the run metrics in `runs/seq2/`. Follows "
  "[`seq2.md`](seq2.md), whose findings 2 and 3 these runs test. Same protocol as sequence 2: 1D fits = 5 inits "
  "(fit to P*) and 3 seeds (maximum likelihood, Adam then L-BFGS); 2 × 4-bit fits = 1 run each, Adam 500 then "
  "L-BFGS capped at 6,000.\n")

# ------------------------------------------------------------------ var2d
T4, T4i, T3 = TG.VAR2D, TG.VAR2DI, TG.VAR2D3
FINDINGS_AT = len(L)  # the findings paragraph is inserted here once every table is built
rows = []
for lab, tgt, circ in (("anc2, bits x₁ then x₂", "var2d", "anc2"), ("anc2x: + cross entanglers r ↔ r+4", "var2d", "anc2x"),
                       ("anc2, interleaved bits", "var2di", "anc2"),
                       ("anc2x, 5 layers", "var2d", "anc2x-L5")):
    for mode in ("ceiling", "mle"):
        rs = runs(tgt, mode, circ)
        if rs:
            m = best(rs)["metrics"] if mode == "ceiling" else rs[0]["metrics"]
            rows.append((lab, mode, rs[0]["n_params"], m))
w("## 1. var2d: does coupling the coordinates' bits fix the correlation?\n")
w("Sequence 2 found the anc2 circuit missing the stationary correlation of (x₁, x₂) on the 2 × 4-bit grid "
  "(error about −0.18 to −0.20) and conjectured that the nearest-neighbour output chain, which links the two "
  "coordinates only through x₁'s last bit and x₂'s first, was the cause. Two fixes were tested on the same grid: "
  "**anc2x** adds controlled R_y between output bit r of x₁ and bit r of x₂ (both directions, every layer); "
  "**interleaved bits** keeps the anc2 circuit and reorders the output bits (x₁⁰ x₂⁰ x₁¹ x₂¹ …), so the chain itself "
  "links bit r of x₁ to bit r of x₂.\n")
w("| Circuit | Mode | Angles | Weighted TV | Stationary TV | Corr. error | Lag-1 error | Cond. sd rel. error |")
w("| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: |")
for lab, mode, n, m in rows:
    w(f"| {lab} | {'fit to P*' if mode == 'ceiling' else 'max. likelihood'} | {n} | {f(m['weighted_tv'])} | "
      f"{f(m['stationary_tv'])} | {m['corr_err']:+.3f} | {f(lagerr(m, 2))} | "
      f"{f(max(m['cond_sd_rel_0'], m['cond_sd_rel_1']))} |")
r4 = refs(T4)
w(f"| true family, fitted | – | 7 | {f(r4['parametric']['weighted_tv'])} | {f(r4['parametric']['stationary_tv'])} | "
  f"{r4['parametric']['corr_err']:+.3f} | {f(lagerr(r4['parametric'], 2))} | "
  f"{f(max(r4['parametric']['cond_sd_rel_0'], r4['parametric']['cond_sd_rel_1']))} |")
w(f"| tabular counts | – | 65,280 | {f(r4['tabular']['weighted_tv'])} | {f(r4['tabular']['stationary_tv'])} | "
  f"{r4['tabular']['corr_err']:+.3f} | {f(lagerr(r4['tabular'], 2))} | "
  f"{f(max(r4['tabular']['cond_sd_rel_0'], r4['tabular']['cond_sd_rel_1']))} |\n")

r3 = runs("var2d3", "ceiling", "anc2")
if r3:
    corr3 = [r["metrics"]["corr_err"] for r in r3]
    w(f"**At 2 × 3 bits the problem does not appear.** The plain anc2 circuit, fitted to P* on the same process binned "
      f"on 8 × 8 cells, reaches weighted TV {f(min(r['metrics']['weighted_tv'] for r in r3))}–"
      f"{f(max(r['metrics']['weighted_tv'] for r in r3))} with correlation errors {min(corr3):+.3f} to "
      f"{max(corr3):+.3f} over {len(r3)} inits. The coarse grid is too easy to discriminate between the fixes, so they "
      f"were tested directly at 2 × 4 bits; the other 3-bit runs were stopped. (At 3 bits P*, which conditions on bin "
      f"centres, also sits far from the binned data: the fitted family scores {f(refs(T3)['parametric']['weighted_tv'])} "
      f"against it.)\n")

# ------------------------------------------------------------------ merton
w("## 2. merton: depth\n")
w("| Circuit | Angles | Fit to P*: best | median | Max. likelihood: median | Cond. sd rel. error (ML median) | "
  "Tail TV (ML median) | Tight (ML) |")
w("| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |")
mrows = {}
for circ, lab in (("anc2", "anc2, 3 layers"), ("anc2-L4", "anc2, 4 layers"), ("anc2-L5", "anc2, 5 layers")):
    c, m_ = runs("merton", "ceiling", circ), runs("merton", "mle", circ)
    if not c:
        continue
    mrows[circ] = (c, m_)
    w(f"| {lab} | {c[0]['n_params']} | {f(best(c)['metrics']['weighted_tv'])} | {f(med(c, 'weighted_tv'))} | "
      f"{f(med(m_, 'weighted_tv'))} | {f(med(m_, 'cond_sd_rel_0'))} | {f(med(m_, 'tail_tv'))} | "
      f"{sum(r['tight_pass'] for r in m_)}/{len(m_)} |")
rm = refs(TG.MERTON)
w(f"| true family, fitted | 5 | – | – | {f(rm['parametric']['weighted_tv'])} | {f(rm['parametric']['cond_sd_rel_0'])} | "
  f"{f(rm['parametric']['tail_tv'])} | ✓ |")
w(f"| tabular counts | 992 | – | – | {f(rm['tabular']['weighted_tv'])} | {f(rm['tabular']['cond_sd_rel_0'])} | "
  f"{f(rm['tabular']['tail_tv'])} | ✓ |\n")


# ------------------------------------------------------------------ figure
def fig_merton(path):
    T = TG.MERTON
    z = T.z
    P = T.exact_kernel()
    fig, axes = plt.subplots(1, 3, figsize=(11, 3.2), sharey=True)
    cols = {"anc2": OI["sky"], "anc2-L4": OI["blue"], "anc2-L5": OI["vermillion"]}
    for ax, x0 in zip(axes, (-2.0, 0.0, 2.0)):
        i = int(np.argmin(np.abs(z - x0)))
        ax.plot(z, P[i], color=OI["black"], lw=2.2, drawstyle="steps-mid", label="exact P*")
        for circ, (_, m_) in mrows.items():
            if m_:
                b = min(m_, key=lambda r: r["metrics"]["weighted_tv"])
                K = np.load(b["dir"] / "kernel.npy")
                depth = {"anc2": 3, "anc2-L4": 4, "anc2-L5": 5}[circ]
                ax.plot(z, K[i], color=cols[circ], lw=1.5, drawstyle="steps-mid",
                        label=f"anc2, {depth} layers, max. likelihood")
        ax.set_yscale("log")
        ax.set_ylim(1e-4, 0.6)
        ax.set_title(f"row x_t = {z[i]:+.2f}", fontsize=9)
        ax.set_xlabel("x_t+1")
        for s in ("top", "right"):
            ax.spines[s].set_visible(False)
    axes[0].set_ylabel("P(x_t+1 bin | x_t), log scale")
    h, lab = axes[0].get_legend_handles_labels()
    fig.legend(h, lab, loc="lower center", ncol=4, fontsize=8, frameon=False, bbox_to_anchor=(0.5, -0.04))
    fig.suptitle("merton: kernel rows by depth (log scale shows the jump shoulder and the tails)", fontsize=9)
    fig.tight_layout(rect=(0, 0.07, 1, 1))
    fig.savefig(path, dpi=170, bbox_inches="tight")
    plt.close(fig)


if mrows:
    fig_merton(FIGS / "seq2fu_merton_depth.png")
    w("![merton rows by depth](../figs/seq2fu_merton_depth.png)\n")

# ------------------------------------------------------------------ findings (read from the same runs)
def one(tgt, mode, circ):
    rs = runs(tgt, mode, circ)
    return (best(rs) if mode == "ceiling" else rs[0])["metrics"] if rs else None


a_c, a_m = one("var2d", "ceiling", "anc2"), one("var2d", "mle", "anc2")
x_c, x_m = one("var2d", "ceiling", "anc2x"), one("var2d", "mle", "anc2x")
i_c = one("var2di", "ceiling", "anc2")
F = ["## Findings\n"]
if a_c and x_c and i_c:
    F.append(f"1. **var2d: coupling the coordinates' bits helps, but does not fix the correlation.** Fitted to P*, "
             f"the cross entanglers (anc2x, +24 angles) lower the weighted TV from {f(a_c['weighted_tv'])} to "
             f"{f(x_c['weighted_tv'])} and the correlation error from {a_c['corr_err']:+.3f} to {x_c['corr_err']:+.3f}; "
             f"interleaving the bits (same circuit) barely moves either ({f(i_c['weighted_tv'])}, "
             f"{i_c['corr_err']:+.3f}). "
             + (f"Trained on the data by likelihood, anc2x reaches {f(x_m['weighted_tv'])} (anc2: "
                f"{f(a_m['weighted_tv'])}), level with the tabular counts ({f(r4['tabular']['weighted_tv'])}) and still "
                f"{f(x_m['weighted_tv'] / r4['parametric']['weighted_tv'], 1)}× the fitted family "
                f"({f(r4['parametric']['weighted_tv'])}), with correlation error {x_m['corr_err']:+.3f}. " if x_m and a_m else "")
             + "So the missing link between the coordinates' bits was part of the problem, not most of it.")
d_c, d_m = one("var2d", "ceiling", "anc2x-L5"), one("var2d", "mle", "anc2x-L5")
if d_c and d_m:
    snap = json.loads((SEQ2 / "var2d" / "ceiling" / "anc2x-L5" / "0" / "snapshot_6000.json").read_text())["metrics"]
    F.append(f"2. **var2d: depth does most of the rest.** With 5 layers (anc2x, "
             f"{runs('var2d', 'ceiling', 'anc2x-L5')[0]['n_params']} angles; fits run as resumable segments, 10,000 "
             f"L-BFGS iterations) the fit to P* reaches {f(d_c['weighted_tv'])} ({f(snap['weighted_tv'])} at 6,000 "
             f"iterations, the 3-layer budget), correlation error {d_c['corr_err']:+.3f}; by likelihood on the data "
             f"{f(d_m['weighted_tv'])}, correlation error {d_m['corr_err']:+.3f}, conditional-sd error "
             f"{f(max(d_m['cond_sd_rel_0'], d_m['cond_sd_rel_1']))}. That is better than the tabular counts "
             f"({f(r4['tabular']['weighted_tv'])}), the regime where a compact model should pay off, but still "
             f"{f(d_m['weighted_tv'] / r4['parametric']['weighted_tv'], 1)}× the fitted 7-parameter family "
             f"({f(r4['parametric']['weighted_tv'])}). A 4-layer run was started and stopped to free the machine for "
             f"sequence 3; its partial checkpoint is in `runs/seq2/var2d/ceiling/anc2x-L4/0/ckpt/`.")
if "anc2-L5" in mrows and "anc2" in mrows:
    c3, m3 = mrows["anc2"]
    c5, m5 = mrows["anc2-L5"]
    F.append(f"3. **merton: depth closes most of the gap.** From 3 to 5 layers (215 → {c5[0]['n_params']} angles) the "
             f"best fit to P* goes from {f(best(c3)['metrics']['weighted_tv'])} to {f(best(c5)['metrics']['weighted_tv'])}, "
             f"and maximum likelihood on the data from {f(med(m3, 'weighted_tv'))} to {f(med(m5, 'weighted_tv'))} "
             f"(median; tabular {f(rm['tabular']['weighted_tv'])}, fitted family {f(rm['parametric']['weighted_tv'])}). "
             f"The jump shoulder is now held: conditional-sd error {f(med(m3, 'cond_sd_rel_0'))} → "
             f"{f(med(m5, 'cond_sd_rel_0'))}, and {sum(r['tight_pass'] for r in m5)} of {len(m5)} likelihood runs pass "
             f"the tight checks ({sum(r['tight_pass'] for r in m3)} of {len(m3)} at 3 layers). The circuit still needs {c5[0]['n_params'] / 5:.0f} times the parameters of "
             f"the fitted family to come within {med(m5, 'weighted_tv') / rm['parametric']['weighted_tv']:.1f}× of it.")
F.append("")
L[FINDINGS_AT:FINDINGS_AT] = F
(ROOT / "reports" / "seq2_followups.md").write_text("\n".join(L))
print("\n".join(L))
