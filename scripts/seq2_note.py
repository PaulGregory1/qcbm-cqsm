"""Render reports/seq2.md from runs/seq2/summary.json and runs/seq2/tables.json (scripts/seq2_report.py).
Every number in the note is read from those files.

Run: ./.venv/bin/python scripts/seq2_report.py && ./.venv/bin/python scripts/seq2_note.py
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
S = json.loads((ROOT / "runs" / "seq2" / "summary.json").read_text())
TAB = json.loads((ROOT / "runs" / "seq2" / "tables.json").read_text())
T = S["targets"]


def f(x, n=3):
    return f"{x:.{n}f}"


def g(t, c, mode, stat="median", key="weighted_tv"):
    C = T[t]["circuits"].get(c, {}).get(mode)
    return C[stat][key] if C else float("nan")


def ref(t, r, key="weighted_tv"):
    return T[t]["references"][r][key]


def tight(t, c, mode):
    C = T[t]["circuits"].get(c, {}).get(mode)
    return f"{C['n_tight_pass']}/{C['n']}" if C else "–"


def n_tight_data():
    return sum(C[m]["n_tight_pass"] for t in T for C in T[t]["circuits"].values() for m in ("mle", "train") if m in C)


def n_data():
    return sum(C[m]["n"] for t in T for C in T[t]["circuits"].values() for m in ("mle", "train") if m in C)


def sink_steps(t):
    s = [r["steps"] for C in T[t]["circuits"].values() for r in C.get("train", {}).get("runs", [])]
    return min(s), max(s)


def sink_lag(t):
    import statistics
    return statistics.median(abs(r["lag1_0"] - r["lag1_exact_0"])
                             for C in T[t]["circuits"].values() for r in C.get("train", {}).get("runs", []))


v2 = T["var2d"]
v2c = v2["circuits"]
cap = json.loads((ROOT / "runs" / "seq2" / "extra" / "var2d_ceiling_anc2_cap2000" / "metrics.json").read_text())
L = []
w = L.append
w("# Sequence 2 — harder Markov targets\n")
w("Generated by `scripts/seq2_note.py` from `runs/seq2/summary.json` (aggregated by `scripts/seq2_report.py`). "
  "Follows [`seq1.md`](seq1.md).\n")

w("## Set-up\n")
w(f"Three targets (`src/archb/targets.py`), each with a closed-form or quadrature exact kernel P* (checked against "
  f"Monte Carlo in `tests/test_targets.py`), 2,000 trajectories × 50 steps after a 200-step burn-in "
  f"({T['arch']['data']['n_transitions']:,} transitions), Gray code per coordinate:\n")
w(f"- **arch**: x′ = 0.8 x + √(0.09 + 0.3 x²) ξ, 5 bits on [−4, 4]. The row's width depends on the input "
  f"(conditional sd from 0.31 in the central bins to 2.1 in the edge bins), not only its centre.")
w(f"- **merton**: x′ = 0.9 x + 0.1 + 0.3 ξ + J (−1 + 0.3 η), J ~ Bernoulli(0.1), 5 bits on [−4, 4]. Each row is "
  f"a main mode plus a 10% downward-jump component one unit lower, which shows as a left shoulder rather than a "
  f"second peak at this resolution.")
w(f"- **var2d**: x′ = A x + e, A = [[0.8, 0], [0.3, 0.7]], noise sd 0.5 on both coordinates with correlation 0.5, "
  f"2 × 4 bits on [−3.5, 3.5]². {v2['K']} states: rows are joint laws of two coupled, correlated variables.\n")
w("Circuits from sequence 1, 3 layers: B0 (no ancilla), anc1, anc2 (`archb.variants`, now for any register size; "
  "var2d uses 8 input + 8 output qubits). References: the target's **true parametric family fitted by maximum "
  "likelihood** to the same binned data (3, 5 and 7 parameters), the tabular counts (+0.1), the i.i.d. oracle.\n")
w("Protocol. 1D targets, as sequence 1: fit to P* (5 inits), maximum likelihood on the data (3 seeds, Adam then "
  "L-BFGS), Sinkhorn on the data (3 seeds, converged-solver settings). **var2d, reduced** because one gradient "
  "costs about 0.75–2.4 s on the 2-core machine used (1 ms in 1D): 1 fit to P* and 1 likelihood fit per circuit, "
  "Adam 500 steps then L-BFGS capped at 6,000 iterations, no Sinkhorn.\n")
w("Tight checks: weighted TV ≤ 0.05, stationary TV ≤ 0.02, lag-1 autocorrelation within 0.02, conditional-mean "
  "RMSE ≤ 0.05 stationary sd and mean relative error of the conditional sd ≤ 10%, for every coordinate.\n")

w("## Findings\n")
w(f"1. **arch: the sequence 1 recipe carries over.** Ancillas again make the difference: best fit to P* "
  f"{f(g('arch', 'B0', 'ceiling', 'best'))} (B0), {f(g('arch', 'anc1', 'ceiling', 'best'))} (anc1), "
  f"{f(g('arch', 'anc2', 'ceiling', 'best'))} (anc2), against {f(ref('arch', 'parametric'))} for the fitted true "
  f"family. Trained on the data by maximum likelihood: {f(g('arch', 'B0', 'mle'))} → {f(g('arch', 'anc1', 'mle'))} → "
  f"{f(g('arch', 'anc2', 'mle'))} (medians), the level of the tabular counts ({f(ref('arch', 'tabular'))}) and "
  f"about {f(g('arch', 'anc2', 'mle') / ref('arch', 'parametric'), 1)}× the fitted family. The input-dependent "
  f"spread is learned: conditional-sd error {f(g('arch', 'anc2', 'mle', 'median', 'cond_sd_rel_0'))} for anc2 "
  f"against {f(g('arch', 'B0', 'mle', 'median', 'cond_sd_rel_0'))} for B0. No likelihood run passes the tight checks "
  f"({tight('arch', 'anc2', 'mle')} for anc2): for anc2 the median conditional-mean RMSE is "
  f"{f(g('arch', 'anc2', 'mle', 'median', 'cond_mean_rmse_0'))} sd (bound 0.05) and the median lag-1 error "
  f"{f(abs(g('arch', 'anc2', 'mle', 'median', 'lag1_0') - g('arch', 'anc2', 'mle', 'median', 'lag1_exact_0')))} "
  f"(bound 0.02), just over, with the tail rows the weak part (tail TV {f(g('arch', 'anc2', 'mle', 'median', 'tail_tv'))}).")
w(f"2. **merton: ancillas help, but even the fit to P* stays well above the fitted family.** Best fit to P*: "
  f"{f(g('merton', 'B0', 'ceiling', 'best'))} (B0), {f(g('merton', 'anc1', 'ceiling', 'best'))} (anc1), "
  f"{f(g('merton', 'anc2', 'ceiling', 'best'))} (anc2), against {f(ref('merton', 'parametric'))} for the family. "
  f"Maximum likelihood: {f(g('merton', 'anc2', 'mle'))} for anc2 (median), **worse than the tabular counts** "
  f"({f(ref('merton', 'tabular'))}). "
  f"The jump shoulder is the hard part: conditional-sd error {f(g('merton', 'anc2', 'mle', 'median', 'cond_sd_rel_0'))} "
  f"for anc2 by likelihood, against {f(ref('merton', 'parametric', 'cond_sd_rel_0'))} for the family. A 3-layer "
  f"circuit with two ancillas does not hold a second, wider component under every row.")
w(f"3. **var2d: at {v2['K']} states the circuit is the bottleneck, and it does worse than the tabular counts.** "
  f"Fit to P*: {f(g('var2d', 'B0', 'ceiling', 'best'))} (B0)"
  + (f", {f(g('var2d', 'anc1', 'ceiling', 'best'))} (anc1)" if "anc1" in v2c and "ceiling" in v2c["anc1"] else "")
  + f", {f(g('var2d', 'anc2', 'ceiling', 'best'))} (anc2); maximum likelihood on the data: "
  f"{f(g('var2d', 'B0', 'mle', 'best'))} (B0)"
  + (f", {f(g('var2d', 'anc1', 'mle', 'best'))} (anc1)" if "anc1" in v2c and "mle" in v2c["anc1"] else "")
  + f", {f(g('var2d', 'anc2', 'mle', 'best'))} (anc2). References: fitted family {f(ref('var2d', 'parametric'))}, "
  f"tabular {f(ref('var2d', 'tabular'))}. This is the regime where a compact model should pay off (the tabular "
  f"kernel, {v2['K'] * (v2['K'] - 1):,} free numbers for {v2['data']['n_transitions']:,} transitions, gets lag-1 "
  f"wrong by {f(max(abs(ref('var2d', 'tabular', f'lag1_{k}') - ref('var2d', 'tabular', f'lag1_exact_{k}')) for k in (0, 1)), 2)}), "
  f"and the circuit does not take it. The step 0 ceiling is not a convergence artefact: with the L-BFGS cap raised "
  f"from 2,000 to 6,000 iterations the anc2 fit moved from {f(cap['metrics']['weighted_tv'])} to "
  f"{f(g('var2d', 'anc2', 'ceiling', 'best'))}. The clearest failure is the **correlation between the two "
  f"coordinates**: stationary correlation error {g('var2d', 'anc2', 'mle', 'best', 'corr_err'):+.3f} for anc2 by "
  f"likelihood ({ref('var2d', 'parametric', 'corr_err'):+.3f} for the fitted family). A plausible reading, not "
  f"tested: the output entangler is a nearest-neighbour chain over the 8 output qubits in the order (x₁ bits, x₂ "
  f"bits), so the only direct link between the coordinates is x₁'s least significant bit to x₂'s most significant "
  f"bit, plus the ancillas; correlated noise needs coupling between the high-order bits of both.")
w(f"4. **Sinkhorn stays far behind maximum likelihood on the 1D targets** (anc2 medians: arch "
  f"{f(g('arch', 'anc2', 'train'))} vs {f(g('arch', 'anc2', 'mle'))}, merton {f(g('merton', 'anc2', 'train'))} vs "
  f"{f(g('merton', 'anc2', 'mle'))}), and its runs stop early ({sink_steps('arch')[0]}–{sink_steps('arch')[1]} steps "
  f"on arch, {sink_steps('merton')[0]}–{sink_steps('merton')[1]} on merton) with lag-1 close to exact (median "
  f"error {f(sink_lag('arch'))} on arch and {f(sink_lag('merton'))} on merton, all circuits): the same pattern as sequence 1, where "
  f"transport got the dynamics' moments right and the rows wrong.")
w(f"5. **Tight checks.** Passed by the fitted family on all three targets and by the tabular counts on the two 1D "
  f"targets only. Among circuits, only fits to P* pass (arch: {tight('arch', 'anc2', 'ceiling')} anc2, "
  f"{tight('arch', 'anc1', 'ceiling')} anc1); {n_tight_data()} of {n_data()} runs trained on data pass.\n")

w("## What this means\n")
w("- The ingredients found in sequence 1 (ancillas, Gray, likelihood, L-BFGS) generalize to a row width that "
  "depends on the input, partly to a jump component, and **not to the 2D scale** where a compact model would "
  "matter. There, the ansatz itself is the limit, not training or data.")
w("- **No quantum advantage is shown or claimed**: on every target the fitted true family (3–7 parameters) does "
  "better than the best circuit (119–416 angles).")
w("- Next steps, cheapest first: (a) on var2d, an output entangler between corresponding bits of the two "
  "coordinates (r ↔ r + 4) or interleaved bit order, tested first at 2 × 3 bits where the full protocol is cheap; "
  "(b) on merton, depth (4–5 layers) with anc2; (c) sequence 3 (non-Markov, quantum memory register) as planned.\n")

for name, title in (("arch", "arch"), ("merton", "merton"), ("var2d", "var2d (reduced protocol)")):
    w(f"## {title}\n")
    w(TAB[name] + "\n")
w("Fit to P* rows give the best of the inits (by the fit objective); other circuit rows give medians over seeds; "
  "Tight = runs passing all tight checks.\n")
w("![weighted TV](../figs/seq2_weighted_tv.png)\n")
w("![arch rows](../figs/seq2_rows_arch.png)\n")
w("![merton rows](../figs/seq2_rows_merton.png)\n")
w("![var2d](../figs/seq2_var2d.png)\n")

w("## Deviations from the plan\n")
w("- **Gray code only.** Sequence 1 found Gray at least as good as binary under every objective; dropping binary "
  "halves the runs.")
w("- **5 step 0 inits** instead of 10 for the 1D targets.")
w("- **var2d reduced protocol** (above), and no Sinkhorn on var2d. The plan's check on the Sinkhorn cost for var2d "
  "(4 axes of 16 points, run axis by axis) was not needed as a result.")
w("- **ε = 0.01 kept** for Sinkhorn on [−4, 4] grids, where one bin squared is 0.0625 instead of 0.035.\n")

w("## Reproduce\n")
w("```bash\nfor t in arch merton; do for m in ceiling mle train; do ./.venv/bin/python scripts/run_seq2.py $t $m; done; done\n"
  "./.venv/bin/python scripts/run_seq2.py var2d ceiling\n./.venv/bin/python scripts/run_seq2.py var2d mle\n"
  "./.venv/bin/python scripts/seq2_report.py && ./.venv/bin/python scripts/seq2_note.py\n```\n")

(ROOT / "reports" / "seq2.md").write_text("\n".join(L))
